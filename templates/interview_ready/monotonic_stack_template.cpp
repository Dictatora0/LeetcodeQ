/*
 * ============================================================================
 * 第六部分：易错点
 * ============================================================================
 */

/*
 * 【常见错误 1：单调性写反】
 * ❌ 题目要找下一个更大，却用了递增栈
 * ✅ 保持“栈顶最大程度接近被弹出条件”
 *
 * 【常见错误 2：忘记处理重复值】
 * ❌ 直接用 > 或 <，导致等值场景重复统计
 * ✅ 按题意决定严格/非严格比较符号
 *
 * 【常见错误 3：柱状图没加哨兵】
 * ❌ 循环结束后仍有元素未结算
 * ✅ 末尾加 0 或额外清栈
 *
 * 【常见错误 4：栈存值导致宽度算错】
 * ✅ 统一存索引，宽度 = i - st.top() - 1
 */

