// ============================================================================
// 变体 1：每日温度
// LeetCode 739: Daily Temperatures
// ============================================================================

class Solution_DailyTemperatures {
public:
    vector<int> dailyTemperatures(vector<int>& temperatures) {
        int n = temperatures.size();
        vector<int> result(n, 0);
        stack<int> st;  // 单调递减栈

        for (int i = 0; i < n; i++) {
            while (!st.empty() && temperatures[i] > temperatures[st.top()]) {
                int idx = st.top();
                st.pop();
                result[idx] = i - idx;  // 天数差
            }

            st.push(i);
        }

        return result;
    }
};

// ============================================================================
// 变体 2：柱状图中最大的矩形
// LeetCode 84: Largest Rectangle in Histogram
// ============================================================================

class Solution_LargestRectangle {
public:
    int largestRectangleArea(vector<int>& heights) {
        stack<int> st;
        heights.push_back(0);  // 哨兵
        int maxArea = 0;

        for (int i = 0; i < heights.size(); i++) {
            while (!st.empty() && heights[i] < heights[st.top()]) {
                int h = heights[st.top()];
                st.pop();

                int w = st.empty() ? i : i - st.top() - 1;
                maxArea = max(maxArea, h * w);
            }

            st.push(i);
        }

        return maxArea;
    }
};

// ============================================================================
// 变体 3：接雨水
// LeetCode 42: Trapping Rain Water
// ============================================================================

class Solution_Trap {
public:
    int trap(vector<int>& height) {
        stack<int> st;
        int water = 0;

        for (int i = 0; i < height.size(); i++) {
            while (!st.empty() && height[i] > height[st.top()]) {
                int bottom = st.top();
                st.pop();

                if (st.empty()) break;

                int left = st.top();
                int h = min(height[left], height[i]) - height[bottom];
                int w = i - left - 1;
                water += h * w;
            }

            st.push(i);
        }

        return water;
    }
};

// ============================================================================
// 变体 4：下一个更大元素 I
// LeetCode 496: Next Greater Element I
// ============================================================================

class Solution_NextGreaterElement {
public:
    vector<int> nextGreaterElement(vector<int>& nums1, vector<int>& nums2) {
        unordered_map<int, int> nextGreater;
        stack<int> st;

        // 先处理 nums2
        for (int num : nums2) {
            while (!st.empty() && num > st.top()) {
                nextGreater[st.top()] = num;
                st.pop();
            }
            st.push(num);
        }

        // 查询 nums1
        vector<int> result;
        for (int num : nums1) {
            result.push_back(nextGreater.count(num) ? nextGreater[num] : -1);
        }

        return result;
    }
};

