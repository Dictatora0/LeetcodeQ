// ============================================================================
// 模板 1：单调递减栈（找下一个更大元素）
// 时间复杂度：O(n)
// 空间复杂度：O(n)
// ============================================================================

class MonotonicDecreasingStack {
public:
    vector<int> nextGreaterElement(vector<int>& nums) {
        int n = nums.size();
        vector<int> result(n, -1);
        stack<int> st;  // 存储下标

        for (int i = 0; i < n; i++) {
            // 当前元素大于栈顶，栈顶找到了答案
            while (!st.empty() && nums[i] > nums[st.top()]) {
                int idx = st.top();
                st.pop();
                result[idx] = nums[i];
            }

            st.push(i);
        }

        return result;
    }
};

// ============================================================================
// 模板 2：单调递增栈（找下一个更小元素）
// 时间复杂度：O(n)
// 空间复杂度：O(n)
// ============================================================================

class MonotonicIncreasingStack {
public:
    vector<int> nextSmallerElement(vector<int>& nums) {
        int n = nums.size();
        vector<int> result(n, -1);
        stack<int> st;

        for (int i = 0; i < n; i++) {
            // 当前元素小于栈顶，栈顶找到了答案
            while (!st.empty() && nums[i] < nums[st.top()]) {
                int idx = st.top();
                st.pop();
                result[idx] = nums[i];
            }

            st.push(i);
        }

        return result;
    }
};

