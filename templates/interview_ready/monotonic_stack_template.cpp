/*
 * 【如何快速识别单调栈题目】
 *
 * ✅ 关键词识别：
 * 1. "下一个更大/更小元素" - 90% 是单调栈
 * 2. "左边/右边第一个..." - 单调栈
 * 3. "柱状图" - 单调栈
 * 4. "温度" - 单调栈
 * 5. "接雨水" - 单调栈
 *
 * ✅ 题目特征：
 * - 需要找相邻关系
 * - 需要维护最大/最小值
 * - 一维数组问题
 *
 * ❌ 不适合单调栈：
 * - 需要排序
 * - 二维问题
 * - 需要全局最值
 */

