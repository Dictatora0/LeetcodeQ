/*
题目 / 示例名称：最大奇数乘积子集
核心知识点：奇偶性、计数、充要条件
适用场景：题目要求“选尽可能多元素，使乘积满足奇偶条件”
关键思路：
1. 乘积是奇数，当且仅当所有因子都是奇数。
2. 所以要选尽可能多元素，唯一能选的就是所有奇数。
3. 如果一个奇数都没有，就无法选出非空奇数乘积子集，答案为 -1。
时间复杂度：O(n)
空间复杂度：O(1)
常见错误：
1. 试图做子集搜索，完全没必要。
2. 只想到“至少要有一个奇数”，却没意识到偶数一旦选入就会让乘积变偶。
3. 把 `x & 1` 当成更高级的写法，但解释不清楚；基础题更推荐 `x % 2 != 0`。
示例输入：
4
1
7
4
2 4 6 8
4
1 3 5 7
6
1 2 3 4 5 6
示例输出：
1
-1
4
3
手动推演：
第四组里奇数只有 1、3、5，共 3 个。
如果把任何一个偶数加进去，乘积立刻变成偶数，所以不能选。
对比说明：
- `x % 2 != 0`：更易读，适合基础题。
- `x & 1`：位运算题常见，但这里不是理解重点。
*/

#include <iostream>

using namespace std;

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    if (!(cin >> t)) {
        return 0;
    }

    while (t--) {
        int n;
        cin >> n;

        int odd_count = 0;
        for (int i = 0; i < n; ++i) {
            long long x;
            cin >> x;

            // 乘积想保持奇数，这个元素本身必须是奇数。
            if (x % 2 != 0) {
                ++odd_count;
            }
        }

        if (odd_count == 0) {
            // 一个奇数都没有，就无法选出非空奇数乘积子集。
            cout << -1 << '\n';
        } else {
            // 想选得尽可能多，就把所有奇数都选上。
            cout << odd_count << '\n';
        }
    }

    return 0;
}
